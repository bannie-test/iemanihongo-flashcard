"""Builds data/chars.js: stroke paths and kanji info for every character
the vocabulary in data/words.js uses (kanji, hiragana and the derived katakana).

Usage:
    python3 tool/build_web_chars.py [path/to/kanji.json]

Stroke data is downloaded from the KanjiVG repository on GitHub (CC BY-SA 3.0)
for characters that data/chars.js does not have yet.
Kanji meanings and Hán Việt readings come from the optional kanji.json
(the iemanihongo app's assets/data/kanji.json); without it, the kanji info
already in data/chars.js is kept, and new kanji get stroke data only.
"""
import json, os, re, sys, urllib.request

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.join(here, '..')
dest = os.path.join(root, 'data', 'chars.js')
words_js = open(os.path.join(root, 'data', 'words.js'), encoding='utf-8').read()

# What data/chars.js already holds, so only new characters are downloaded.
old_strokes, old_kanji = {}, {}
if os.path.exists(dest):
    text = open(dest, encoding='utf-8').read()
    m = re.search(r'window\.STROKES = (\{.*?\});\n', text, re.S)
    if m:
        old_strokes = json.loads(m.group(1))
    m = re.search(r'window\.KANJI = (\{.*?\});\n', text, re.S)
    if m:
        old_kanji = json.loads(m.group(1))

kanji_src = {}
if len(sys.argv) > 1:
    kanji_src = json.load(open(sys.argv[1], encoding='utf-8'))

body = words_js[words_js.index('window.WORDS'):]
writings = re.findall(r"\bw: '([^']+)'", body)
readings = re.findall(r"\br: '([^']+)'", body)


def to_kata(s):
    return ''.join(chr(ord(c) + 0x60) if 0x3041 <= ord(c) <= 0x3096 else c for c in s)


chars = sorted(set(''.join(writings) + ''.join(readings) + to_kata(''.join(readings))))

path_re = re.compile(r'<path[^>]*\bid="kvg:[0-9a-f]+-s(\d+)"[^>]*\bd="([^"]+)"')
num_re = re.compile(r'<text transform="matrix\(1 0 0 1 ([\d.]+) ([\d.]+)\)">(\d+)</text>')


def fetch_kanjivg(ch):
    url = f'https://raw.githubusercontent.com/KanjiVG/kanjivg/master/kanji/{ord(ch):05x}.svg'
    try:
        svg = urllib.request.urlopen(url, timeout=20).read().decode('utf-8')
    except Exception:
        return None
    ps = sorted(((int(n), d) for n, d in path_re.findall(svg)), key=lambda t: t[0])
    if not ps:
        return None
    nums = sorted((int(n), float(x), float(y)) for x, y, n in num_re.findall(svg))
    return {'p': [re.sub(r'\s+', ' ', d.strip()) for _, d in ps],
            'n': [[round(x, 1), round(y, 1)] for _, x, y in nums]}


out_strokes, out_kanji, missing = {}, {}, []
for ch in chars:
    data = old_strokes.get(ch) or fetch_kanjivg(ch)
    if data:
        out_strokes[ch] = data
    else:
        missing.append(ch)
    k = kanji_src.get(ch)
    if k:
        out_kanji[ch] = {'hv': k.get('hv', ''), 'm': '; '.join(k.get('m', [])),
                         'on': k.get('on', []), 'kun': k.get('kun', []), 's': k.get('s')}
    elif ch in old_kanji:
        out_kanji[ch] = old_kanji[ch]

with open(dest, 'w', encoding='utf-8') as f:
    f.write('/* Generated by tool/build_web_chars.py. Stroke data: KanjiVG (CC BY-SA 3.0). */\n')
    f.write('window.STROKES = ' + json.dumps(out_strokes, ensure_ascii=False, separators=(',', ':')) + ';\n')
    f.write('window.KANJI = ' + json.dumps(out_kanji, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(len(out_strokes), 'characters with strokes;', len(out_kanji), 'kanji;',
      'missing:', ''.join(missing) or 'none', ';', os.path.getsize(dest), 'bytes')
